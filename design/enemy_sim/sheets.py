"""Every sample character's build, resolved, in one readable file
(2026-10-27): SHEETS.md, next to this script.

builds/ holds the Builder exports and the variants (a base plus edits);
this writes out what each sample_pcs.csv row actually fights with, the
way party.py loads it: Stats, Skills with their Skill Totals, every
Technique copy with its Level and Features, the items, the row's own
play columns, and the fight numbers. make_replays.py rewrites it each
round, so it never drifts from the builds.

    python3 sheets.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import game_data  # noqa: E402
import party  # noqa: E402
import tunables as T  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "SHEETS.md")


def _features(t):
    feats = t.get("features") or []
    if isinstance(feats, dict):
        feats = [{"name": k, "count": v} for k, v in feats.items()]
    return ", ".join(f["name"] + (f" {f['count']}" if int(f["count"]) > 1 else "") for f in feats)


def _level(t):
    lv = t.get("level", 1)
    return lv if isinstance(lv, str) else f"Lv {lv}"


def sheet(name, row):
    build = party.read_build(row["Build"])
    stats, skills = build["statPoints"], build["skillPoints"]
    pc = party.make_pc(name, 1, 0)
    lines = [f"## {name}", ""]
    src = row["Build"]
    with open(os.path.join(party.BUILDS_DIR, src), encoding="utf-8") as f:
        raw = f.read()
    if '"base"' in raw:
        import json
        src += f" (a variant of {json.loads(raw)['base']})"
    lines.append(f"Build: `builds/{src}`. XP {build.get('xpBudget', '?')}. Tier {row['Tier']}.")
    lines.append("")
    lines.append("Stats: " + ", ".join(f"{k} {v}" for k, v in stats.items()) + ".")
    trained = [(k, v, party.skill_total(stats, skills, k)) for k, v in skills.items() if int(v)]
    lines.append("Skills (points, Skill Total): " + ", ".join(f"{k} {v} ({tot})" for k, v, tot in trained) + ".")
    lines.append("")
    lines.append("Techniques:")
    for t in build.get("techniques", ()):
        feats = _features(t)
        lines.append(f"- {game_data.technique_name(t['id'])} ({t['id']}), {_level(t)}" + (f": {feats}" if feats else ""))
    items = [game_data.items().get(i["id"], {}).get("Name", i["id"]) for i in build.get("inventory", ())]
    lines.append("")
    lines.append("Items: " + (", ".join(items) or "none") + ".")
    play = {k: row[k] for k in ("Weapon", "Choices", "Unmodeled", "Play Style", "Battle Tactic", "Bottles Item",
                                "Health") if row.get(k)}
    if play:
        lines.append("Row: " + "; ".join(f"{k} {v}" for k, v in play.items()) + ".")
    reach = pc.get("attack_range") or T.MELEE_RANGE
    lines.append("")
    lines.append(f"In a fight: Health {pc['max_health']}, Speed {pc['speed']}, Reflex {pc['reflex']}; Parry "
                 f"{pc['parry']}, Dodge {pc['dodge']}, Vital {pc['bodily']}, Mental {pc['mental']}, Vigilant "
                 f"{pc['vigilant']}; Resist {pc['physres']} Physical, {pc['elemres']} elemental. Attacks with "
                 f"{pc.get('weapon_name') or row.get('Weapon') or '?'}: {pc['attack_skill']} {pc['skill_total']}, "
                 f"{pc['damage']} {pc['dmg_type']} damage vs {pc['opp_def']}, reach {reach}. Play Style "
                 f"{pc['play_style']}" + (f", Battle Tactic {pc['battle_tactic']}" if pc.get('battle_tactic') else "")
                 + ".")
    extra = []
    for t in pc.get("tech_attacks", ()):
        extra.append(f"{t['via']} x{t['uses']} ({t['skill_total']}, {t['damage']} {t['dmg_type']} vs {t['opp_def']})")
    for h in pc.get("hexes", ()) or ():
        extra.append(f"{h['via']} x{h['uses']} ({h['kind']} {h['amount']} + {h['suit']})")
    if pc.get("maneuver"):
        skip = {"uses", "max", "tech", "level", "kinds", "attack"}
        extra.append("Battle Maneuver copies in order: " + "; ".join(
            f"Level {m['level']}: " + (", ".join(f"{k} {v}" if v is not True else k for k, v in m.items()
                                                 if v and k not in skip) or "no Features")
            for m in pc["maneuvers"]))
    if pc.get("strategy") == "support_healer":
        extra.append(f"Healing Magic: discards {pc.get('heal_cards', 1)}, heals 1 + Hearts + {pc.get('heal_bonus', 0)}, "
                     f"reach {pc.get('heal_range')}")
    if pc.get("passives"):
        extra.append("Passives: " + ", ".join(pc["passives"]))
    if pc.get("techs"):
        extra.append("Encounter Techniques: " + ", ".join(pc["techs"]))
    if extra:
        lines.append("")
        lines += [f"- {e}" for e in extra]
    lines.append("")
    return lines


def main():
    rows = party._rows()
    out = ["# The sample characters, as the sim builds them", "",
           "Generated by `sheets.py` from `sample_pcs.csv` and `builds/` (make_replays.py rewrites it each round); "
           "don't edit by hand. Why each character is built the way it is: `sample_characters.md`.", ""]
    bad = []
    for name, row in rows.items():
        try:
            out += sheet(name, row)
        except Exception as e:  # a row that doesn't load still gets a line, not a crash
            bad.append(name)
            out += [f"## {name}", "", f"Doesn't load: {e}", ""]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"wrote {OUT}: {len(rows)} characters" + (f", {len(bad)} that don't load: {bad}" if bad else ""))


if __name__ == "__main__":
    main()
