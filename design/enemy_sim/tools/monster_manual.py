"""Write MONSTER_MANUAL.md: every monster_manual.csv design as a stat block
(2026-11-04).

Each monster is built the pen-and-paper way (ENEMY_ENCOUNTER_DESIGN.md,
"Building an enemy on paper"): Level and Slots, archetype, loadout and
armor, Strong and Weak Defense, then the Ability budget. The sheet shows
the build, the points it spends and leaves as Health, and the numbers at
Levels 1, 3 and 5 as the simulator builds them (tunables as they stand).
Generated: edit monster_manual.csv, then rerun.

    python3 tools/monster_manual.py
"""
import collections
import os

import _paths  # noqa: E402,F401
import tunables as T  # noqa: E402
import game_data  # noqa: E402
import sample_enemies as se  # noqa: E402
import enemy_builder_pcstyle as eb  # noqa: E402

OUT = os.path.join(_paths.ROOT, "MONSTER_MANUAL.md")
LEVELS = (1, 3, 5)
SLOT_WORD = {0.5: "Minion (½ Slot)", 1.0: "1 Slot", 2.0: "Elite (2 Slots)", 4.0: "Solo boss (4 Slots)"}
SHOW = {"Light Melee": "Light Weapon (no shield)"}
GROUPS = ["Defender", "Striker", "Bruiser", "Strategist", "Backup", "Skirmisher"]


def budget(level):
    return T.V3_PRUNED_ALLOWANCE + T.V3_PRUNED_EXTRA.get(level, 0)


def tally(picks):
    out = collections.Counter(picks)
    return ", ".join(f"{p} ×{n}" if n > 1 else p for p, n in out.items())


def stat_row(e):
    prof = e if e.get("attack_damage") else e.get("backup") or e
    dmg = prof.get("attack_damage") or 0
    acc = prof.get("accuracy")
    vs = prof.get("opp_def") or e.get("opp_def")
    main = ""
    if e["kind"] == "hex":
        main = f"{e['action']} +{e['accuracy']} vs {e['opp_def']}, {e.get('main_effect')} ×{e['effect_stacks']}; backup "
    elif e["kind"] != "attack":
        main = f"{e['action']}: {e.get('main_effect')} {e['effect_stacks']}; backup "
    parry = "—" if e["parry"] < 0 else e["parry"]
    rng = prof.get("attack_range") or 0
    return (f"| {e['level']} | {main}+{acc} vs {vs}, {dmg} {prof.get('dmg_type') or ''}"
            f"{f', range {rng}' if rng else ''} | {parry} | {e['dodge']} | {e['bodily']} | {e['mental']} | "
            f"{e['vigilant']} | {e['physres']} / {e['elemres']} | {e['max_health']} | {e['speed']} |")


def main():
    T.ENEMY_TABLE, T.V3_VERSION, T.V3_PRUNED_ROSTER = "v3", 3, "picks"
    rows = game_data.csv_rows(se._MANUAL_PATH)
    lines = ["# Monster manual (draft)", "",
             "Generated by `tools/monster_manual.py` from `monster_manual.csv`; edit the CSV, not this file.",
             "Each monster is built in the five pen-and-paper steps: Level and Slots, archetype, loadout and armor,",
             f"Strong and Weak Defense, then the Ability budget ({' / '.join(str(budget(L)) for L in range(1, 6))} "
             "points at Levels 1-5; unspent points are Health). The extra points from Level 2 up go to Accuracy +1",
             "first, then Damage +1, then the monster's own Level picks. Numbers are the simulator's build at",
             "Levels 1, 3 and 5. Accuracy includes the weapon's own. Defenses are 8 + Skill Total.",
             "Accuracy +1 can be bought more than once, but can't raise an enemy's Accuracy before its",
             "weapon's own above 10, the player cap.", ""]
    lines += ["| Monster | Slots | Archetype | Action | Armor |", "|---|---|---|---|---|"]
    by_role = sorted(rows, key=lambda r: (GROUPS.index(r["Role"]), r["Name"]))
    for r in by_role:
        act = SHOW.get(r["Action"], r["Action"]) + (f" (backup {r['BackupAction']})" if r["BackupAction"] else "")
        lines.append(f"| {r['Name']} | {SLOT_WORD[float(r['Slots'])]} | {r['Role']} | {act} | {r['Armor']} |")
    lines.append("")
    # Coverage: which monster uses each Ability, and what nobody uses yet.
    used = collections.defaultdict(list)
    for r in rows:
        for p in dict.fromkeys(x.strip() for x in r["PrunedPicks"].split(";") if x.strip()):
            used[p].append(r["Name"])
    catalog = sorted(k for k in eb.ABILITY_HEALTH_V3P
                     if not any(k.startswith(f"{w} (") for w in ("Resist", "Attunement", "Elemental Spell", "Elemental Weapon"))
                     and k not in ("Heavy Weapon", "Parry and Dodge +1"))  # the latter is Dodge +1 now
    catalog += sorted(k for k in used if k not in catalog)
    lines += ["## Coverage", "", "Every Ability in the catalog and the monsters that take it "
              "(element-specific ones by the element used).", ""]
    for k in catalog:
        lines.append(f"- **{k}** ({eb.ABILITY_HEALTH_V3P[k]:g}): " + (", ".join(used[k]) if used.get(k) else "*nobody yet*"))
    lines.append("")
    role = None
    for r in by_role:
        if r["Role"] != role:
            role = r["Role"]
            lines += [f"## {role}s", ""]
        picks = [p.strip() for p in r["PrunedPicks"].split(";") if p.strip()]
        loadout = eb.LOADOUT_HEALTH_V3P.get(r["Action"], 0)
        armor = eb.ARMOR_HEALTH_V3P[r["Armor"]]
        spent = sum(eb.ABILITY_HEALTH_V3P[p] for p in picks) + loadout + armor
        e3 = se.get_enemy(f"{r['Name']}@3")
        # The size's extra points (BigPicks) apart from the Level's extra.
        saved, T.V3_SLOT_BUDGET = T.V3_SLOT_BUDGET, {}
        plain3 = se.get_enemy(f"{r['Name']}@3")["abilities"]
        T.V3_SLOT_BUDGET = saved
        big3 = list(e3["abilities"])
        for p in plain3:
            big3.remove(p)
        extra3 = list(plain3)
        for p in picks:
            if p in extra3:
                extra3.remove(p)
        k = T.V3_SLOT_BUDGET.get(float(r["Slots"]), 1)
        big_line = []
        if k > 1:
            mult = T.V3_SOLO_HEALTH if float(r["Slots"]) == 4 else T.V3_ELITE_HEALTH
            big_line = [f"- **Size:** {k:g} times the points; the extra {budget(1) * (k - 1):g} at Level 1 and "
                        f"{budget(3) * (k - 1):g} at Levels 3-5 buy (in order, as far as they go) "
                        + (tally(big3) or "Health") + f" at Level 3. Health ×{mult:g}"
                        + ("" if float(r["Slots"]) == 2 else ", two turns a round") + "."]
        lines += [f"### {r['Name']}", "", f"*{r['Concept']}*", "",
                  f"- **{SLOT_WORD[float(r['Slots'])]}, {r['Role']}.** {r['BattleTactic']} "
                  f"({'goes for the softest' if r['BattleTactic'] == 'Assassin' else 'keeps its distance' if r['BattleTactic'] == 'Kiting' else 'fights whoever is near'}).",
                  f"- **Loadout:** {SHOW.get(r['Action'], r['Action'])}" + (f", backup {r['BackupAction']}" if r["BackupAction"] else "")
                  + (f", lands {r['MainEffect']}" if r["MainEffect"] else "")
                  + f" ({loadout:g}). **Armor:** {r['Armor']} ({armor:g})"
                  + (f", Medium ({eb.ARMOR_HEALTH_V3P['Medium']:g}) below Level {T.V3_HEAVY_MIN_LEVEL}"
                     if r["Armor"] == "Heavy" and getattr(T, "V3_HEAVY_MIN_LEVEL", None) else "") + ". "
                  f"**Strong:** {r['StrongDefense']}. **Weak:** {r['WeakDefense'] or 'the default for its kind'}.",
                  "- **Picks:** " + ", ".join(f"{k}{' ×' + str(n) if n > 1 else ''} ({eb.ABILITY_HEALTH_V3P[k] * n:g})"
                                              for k, n in collections.Counter(picks).items()),
                  f"- **Points:** the picks, loadout and armor cost {spent:g} of the Level's {budget(1):g} / {budget(2):g} / "
                  f"{budget(3):g} (Levels 1 / 2 / 3-5); what's left buys " + (tally(extra3) or "Health")
                  + " at Level 3, the rest is Health.",
                  *big_line,
                  "", "| Level | Attack | Parry | Dodge | Vital | Mental | Vigilant | Resist (P / E) | Health | Speed |",
                  "|---|---|---|---|---|---|---|---|---|---|"]
        for L in LEVELS:
            lines.append(stat_row(se.get_enemy(f"{r['Name']}@{L}")))
        lines.append("")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("wrote", OUT, len(rows), "monsters")


if __name__ == "__main__":
    main()
